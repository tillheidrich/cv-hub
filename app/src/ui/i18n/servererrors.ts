const LOCALE: Record<UiLang, string> = { de: 'de-DE', en: 'en-GB', fr: 'fr-FR', es: 'es-ES' };

/** Wartezeit als Satzteil: unter zwei Minuten in Sekunden, sonst in Minuten. */
function wait(lang: UiLang, s?: number): string {
  const n = Math.max(1, Math.ceil(s ?? 60));
  const min = n >= 120 ? Math.ceil(n / 60) : 0;
  if (lang === 'en') return min ? `${min} minutes` : `${n} seconds`;
  if (lang === 'fr') return min ? `${min} minutes` : `${n} secondes`;
  if (lang === 'es') return min ? `${min} minutos` : `${n} segundos`;
  return min ? `${min} Minuten` : `${n} Sekunden`;
}
function day(lang: UiLang, iso?: string): string {
  if (!iso) return '';
  try {
    return new Date(iso).toLocaleDateString(LOCALE[lang], lang === 'de'
      ? { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'Europe/Berlin' }
      : { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/Berlin' });
  } catch { return iso.slice(0, 10); }
}

