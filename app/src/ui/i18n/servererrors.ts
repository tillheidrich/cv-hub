export const SERVER_ERRORS_I18N: Record<UiLang, Record<ServerErrorCode, Msg>> = { de: DE, en: EN, fr: FR, es: ES };

/** Rückfall ohne Text vom Server: „Fehler 502“ in der Oberflächensprache. */
export const STATUS_FALLBACK: Record<UiLang, (status: number) => string> = {
  de: s => `Fehler ${s}`,
  en: s => `Error ${s}`,
  fr: s => `Erreur ${s}`,
  es: s => `Error ${s}`,
};
/** Rückfall des PDF-Dienstes ohne Text. */
export const PDF_STATUS_FALLBACK: Record<UiLang, (status: number) => string> = {
  de: s => `PDF-Dienst antwortete mit ${s}`,
  en: s => `The PDF service responded with ${s}`,
  fr: s => `Le service PDF a répondu par une erreur ${s}`,
  es: s => `El servicio de PDF respondió con el error ${s}`,
};

export function isServerErrorCode(code: unknown): code is ServerErrorCode {
  return typeof code === 'string' && (SERVER_ERROR_CODES as readonly string[]).includes(code);
}

/** Satz zu einem Code in der Sprache, oder null bei unbekanntem Code. */
export function serverErrorText(code: unknown, lang: UiLang, data: ServerErrorData = {}): string | null {
  if (!isServerErrorCode(code)) return null;
  const m = (SERVER_ERRORS_I18N[lang] ?? SERVER_ERRORS_I18N.de)[code];
  return typeof m === 'function' ? m(data, lang) : m;
}
